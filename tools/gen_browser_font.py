#!/usr/bin/env python3
"""Writes the browser's fonts as a C header.

NAQ OS has no font files and nothing to draw outlines with, so the browser's
text is drawn from pictures of letters made here, at build time: DejaVu Sans
(and DejaVu Sans Mono for code) at a handful of sizes, regular and bold,
each letter as a small grey-scale picture with 16 levels.

Characters: Windows-1252 codes 32..255, which covers English and western
European text plus curly quotes, dashes, the bullet and the euro sign.

usage: gen_browser_font.py <output header>
needs: python3-pil and the DejaVu fonts (fonts-dejavu-core)
"""
import os
import sys

from PIL import ImageFont

FONT_DIR = '/usr/share/fonts/truetype/dejavu'
SIZES = [10, 12, 14, 16, 18, 21, 24, 32]
FACES = [(s, 0, 0, 'DejaVuSans.ttf') for s in SIZES] + \
        [(s, 1, 0, 'DejaVuSans-Bold.ttf') for s in SIZES] + \
        [(13, 0, 1, 'DejaVuSansMono.ttf'), (13, 1, 1, 'DejaVuSansMono-Bold.ttf')]


def char_for(code):
    try:
        return bytes([code]).decode('cp1252')
    except UnicodeDecodeError:
        return '?'


def main():
    out = []
    data = bytearray()
    out.append('/* Generated by tools/gen_browser_font.py from DejaVu Sans. Do not edit. */')
    out.append('#ifndef BROWSER_FONT_H')
    out.append('#define BROWSER_FONT_H')
    out.append('')
    out.append('typedef struct font_glyph {')
    out.append('    u32 offset;     /* into g_font_pixels: rows of 4-bit grey, two pixels a byte */')
    out.append('    u8 w, h;        /* size of the picture */')
    out.append('    i8 left, top;   /* where it sits: right of the pen, below the line top */')
    out.append('    u8 advance;     /* how far the pen moves */')
    out.append('} font_glyph_t;')
    out.append('')
    out.append('typedef struct font_face {')
    out.append('    u8 size, bold, mono, ascent, height;')
    out.append('    const font_glyph_t* glyphs;     /* for codes 32..255 */')
    out.append('} font_face_t;')
    out.append('')

    faces = []
    for index, (size, bold, mono, name) in enumerate(FACES):
        font = ImageFont.truetype(os.path.join(FONT_DIR, name), size)
        ascent, descent = font.getmetrics()
        rows = []
        for code in range(32, 256):
            ch = char_for(code)
            advance = int(round(font.getlength(ch)))
            box = font.getbbox(ch)
            mask = font.getmask(ch)
            w, h = mask.size
            offset = len(data)
            if w and h:
                pixels = list(mask)
                for y in range(h):
                    for x in range(0, w, 2):
                        a = pixels[y * w + x] >> 4
                        b = (pixels[y * w + x + 1] >> 4) if x + 1 < w else 0
                        data.append((a << 4) | b)
            left = max(-128, min(127, box[0]))
            top = max(-128, min(127, box[1]))
            rows.append('    { %d, %d, %d, %d, %d, %d },' % (offset, min(w, 255), min(h, 255), left, top, min(advance, 255)))
        out.append('static const font_glyph_t g_font_glyphs_%d[224] = {' % index)
        out.extend(rows)
        out.append('};')
        out.append('')
        faces.append('    { %d, %d, %d, %d, %d, g_font_glyphs_%d },' % (size, bold, mono, ascent, ascent + descent, index))

    out.append('#define FONT_FACE_COUNT %d' % len(FACES))
    out.append('')
    out.append('static const font_face_t g_font_faces[FONT_FACE_COUNT] = {')
    out.extend(faces)
    out.append('};')
    out.append('')
    out.append('static const u8 g_font_pixels[%d] = {' % len(data))
    for i in range(0, len(data), 24):
        out.append('    ' + ','.join('%d' % b for b in data[i:i + 24]) + ',')
    out.append('};')
    out.append('')
    out.append('#endif')
    open(sys.argv[1], 'w', newline='\n').write('\n'.join(out) + '\n')
    print('browser font: %d faces, %d KB of pixels' % (len(FACES), len(data) // 1024))


if __name__ == '__main__':
    main()
