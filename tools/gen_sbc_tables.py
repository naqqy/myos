#!/usr/bin/env python3
"""Writes kernel64/bt/sbc_tables64.h: the SBC filter tables as whole numbers.

The kernel has no floating point, so the two tables the encoder needs are
worked out here:

  proto   the 80-tap window from the A2DP specification (8 subbands),
          scaled by 2^24
  cosine  cos((k + 0.5) * (i - 4) * pi / 8) for subband k and tap i,
          scaled by 2^14

usage: gen_sbc_tables.py <output file>
"""
import math
import sys

