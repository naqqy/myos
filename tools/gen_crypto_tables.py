#!/usr/bin/env python3
"""Writes userapps/runtime/sha512_tables.h, and the trusted root list.

SHA-512's constants are defined by arithmetic (the fractional parts of the
cube roots of the first 80 primes, and of the square roots of some primes
for the starting values), so they are worked out here exactly rather than
typed in.

usage:
  gen_crypto_tables.py sha512 <output header>
  gen_crypto_tables.py roots <PEM bundle> <output file>

The roots file is the system's list of trusted certificate authorities
(/etc/ssl/certs/ca-certificates.crt on Debian/Ubuntu, Mozilla's list) in a
form that is easy to read on NAQ OS: for each certificate, its length as
two bytes (high byte first), then the certificate (DER).
"""
import base64
import sys


def primes(count):
    found = []
    n = 2
    while len(found) < count:
        if all(n % p for p in found):
            found.append(n)
        n += 1
    return found


def iroot(value, k):
    """Largest integer r with r**k <= value."""
    lo, hi = 0, 1
    while hi ** k <= value:
        hi *= 2
    while lo + 1 < hi:
        mid = (lo + hi) // 2
        if mid ** k <= value:
            lo = mid
        else:
            hi = mid
    return lo


def frac_root(p, k):
    """First 64 bits of the fractional part of the k-th root of p."""
    return iroot(p << (64 * k), k) & ((1 << 64) - 1)


def write_sha512(path):
    ps = primes(80)
    out = ['/* Generated by tools/gen_crypto_tables.py. Do not edit. */',
           '#ifndef SHA512_TABLES_H', '#define SHA512_TABLES_H', '',
           'static const u64 g_sha512_k[80] = {']
    for i in range(0, 80, 4):
        out.append('    ' + ', '.join('0x%016xull' % frac_root(p, 3) for p in ps[i:i + 4]) + ',')
    out.append('};')
    out.append('')
    out.append('static const u64 g_sha512_start[8] = {')
    out.append('    ' + ', '.join('0x%016xull' % frac_root(p, 2) for p in ps[:8]) + ',')
    out.append('};')
    out.append('')
    out.append('static const u64 g_sha384_start[8] = {')
    out.append('    ' + ', '.join('0x%016xull' % frac_root(p, 2) for p in ps[8:16]) + ',')
    out.append('};')
    out.append('')
    out.append('#endif')
    open(path, 'w', newline='\n').write('\n'.join(out) + '\n')


def write_roots(bundle, path):
    text = open(bundle, encoding='ascii', errors='ignore').read()
    out = bytearray()
    count = 0
    for block in text.split('-----BEGIN CERTIFICATE-----')[1:]:
        body = block.split('-----END CERTIFICATE-----')[0]
        der = base64.b64decode(''.join(body.split()))
        if 0 < len(der) < 65536:
            out += bytes([len(der) >> 8, len(der) & 255]) + der
            count += 1
    open(path, 'wb').write(bytes(out))
    print('trusted roots: %d certificates, %d KB' % (count, len(out) // 1024))


if __name__ == '__main__':
    if sys.argv[1] == 'sha512':
        write_sha512(sys.argv[2])
    else:
        write_roots(sys.argv[2], sys.argv[3])
