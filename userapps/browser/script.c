/* Asking the user (alert and confirm)                                         */
/* -------------------------------------------------------------------------- */

static int js_modal(const char* message, int with_cancel) {
    u64 began = get_ticks();
    i32 box_w = (i32)g_w - 80;
    i32 chars = 0;
    i32 lines = 1;
    int answer = -1;

    if (box_w > 520) {
        box_w = 520;
    }

    chars = (box_w - 32) / GFX_FONT_W;

    /* Break the message into lines of at most `chars` characters. */
    char text_lines[8][72];
    u32 at = 0;
    u32 length = (u32)strlen(message);

    if (chars > 70) {
        chars = 70;
    }

    lines = 0;

    while (at < length && lines < 8) {
        u32 take = 0;
        u32 last_space = 0;

        while (at + take < length && take < (u32)chars && message[at + take] != '\n') {
            if (message[at + take] == ' ') {
                last_space = take;
            }

            take++;
        }

        if (at + take < length && message[at + take] != '\n' && last_space > 0) {
            take = last_space;
        }

        for (u32 i = 0; i < take; i++) {
            char c = message[at + i];

            text_lines[lines][i] = ((u8)c < 32u || (u8)c > 126u) ? '?' : c;
        }

        text_lines[lines][take] = 0;
        lines++;

        at += take;

        while (at < length && (message[at] == ' ' || message[at] == '\n')) {
            at++;

            if (message[at - 1u] == '\n') {
                break;
            }
        }
    }

    if (lines == 0) {
        text_lines[0][0] = 0;
        lines = 1;
    }

    i32 box_h = 40 + lines * 18 + 44;
    i32 bx = ((i32)g_w - box_w) / 2;
    i32 by = ((i32)g_h - box_h) / 2;
    i32 ok_x = with_cancel ? bx + box_w / 2 - 88 : bx + box_w / 2 - 40;
    i32 cancel_x = bx + box_w / 2 + 8;
    i32 button_y = by + box_h - 36;

    paint();

    rect(bx + 4, by + 4, box_w, box_h, 0x00507890u);
    gradient(bx, by, box_w, box_h, 0x00FFFFFFu, 0x00DCF2FCu);
    frame(bx, by, box_w, box_h, COL_BAR_EDGE);
    gradient(bx + 1, by + 1, box_w - 2, 24, COL_BAR_TOP, COL_BAR_BOT);
    text(bx + 10, by + 5, "This page says", 0x0016445Eu);

    for (i32 i = 0; i < lines; i++) {
        text(bx + 16, by + 36 + i * 18, text_lines[i], COL_TEXT);
    }

    button(ok_x, button_y, 80, 24, "OK", 1);

    if (with_cancel) {
        button(cancel_x, button_y, 80, 24, "Cancel", 1);
    }

    win_present(g_window, g_pixels, g_w, g_h);
    sound_play(NAQ_SOUND_NOTIFY);

    while (answer < 0) {
        naq_win_event_t ev;

        while (answer < 0 && win_get_event(g_window, &ev) == 1) {
            if (ev.type == NAQ_WIN_EVENT_CLOSE) {
                g_quit = 1;
                answer = 0;
            } else if (ev.type == NAQ_WIN_EVENT_KEY) {
                if (ev.key == NAQ_KEY_ENTER || ev.key == ' ') {
                    answer = 1;
                } else if (ev.key == NAQ_KEY_ESCAPE) {
                    answer = with_cancel ? 0 : 1;
                }
            } else if (ev.type == NAQ_WIN_EVENT_MOUSE && ev.w == NAQ_MOUSE_PRESS) {
                i32 x = (i32)(((i64)ev.x * (i64)g_w) / (i64)g_window_w);
                i32 y = (i32)(((i64)ev.y * (i64)g_h) / (i64)g_window_h);

                if (y >= button_y && y < button_y + 24) {
                    if (x >= ok_x && x < ok_x + 80) {
                        answer = 1;
                    } else if (with_cancel && x >= cancel_x && x < cancel_x + 80) {
                        answer = 0;
                    }
                }
            }
        }

        if (answer < 0) {
            sleep_ms(16);
        }
    }

    /* Time spent waiting for the user does not count against the script. */
    g_js_deadline += get_ticks() - began;

    return answer;
}

