static JSValue native_log(JSContext* ctx, JSValueConst self, int argc, JSValueConst* argv) {
    (void)self;

    if (argc >= 2) {
        const char* level = JS_ToCString(ctx, argv[0]);
        const char* message = JS_ToCString(ctx, argv[1]);

        if (level && message) {
            js_log(level, message);
        }

        if (level) JS_FreeCString(ctx, level);
        if (message) JS_FreeCString(ctx, message);
    }

    return JS_UNDEFINED;
}

/* load(url): the text of a file from the network, or null. */
static JSValue native_load(JSContext* ctx, JSValueConst self, int argc, JSValueConst* argv) {
    (void)self;

    if (argc < 1) {
        return JS_NULL;
    }

    u64 began = get_ticks();

    if (g_js_loads >= JS_MAX_LOADS || began > g_js_load_until || g_quit) {
        return JS_NULL;
    }

    const char* url = JS_ToCString(ctx, argv[0]);

    if (!url) {
        return JS_NULL;
    }

    JSValue result = JS_NULL;

    if (starts_with(url, "http://") || starts_with(url, "https://")) {
        u8* body = 0;
        u32 length = 0;
        char saved[160];

        g_js_loads++;

        str_copy(saved, g_status, sizeof(saved));
        g_status[0] = 0;
        str_append(g_status, "Loading script ", sizeof(g_status));
        str_append(g_status, url, sizeof(g_status));
        paint_now();

        if (fetch_file(url, &body, &length)) {
            result = JS_NewStringLen(ctx, (const char*)body, length);
        }

        str_copy(g_status, saved, sizeof(g_status));
    }

    JS_FreeCString(ctx, url);

    /* Waiting for the network does not count against the script. */
    g_js_deadline += get_ticks() - began;

    return result;
}

/* eval(code, name): runs a script of the page. Returns whether it finished. */
static JSValue native_eval(JSContext* ctx, JSValueConst self, int argc, JSValueConst* argv) {
    (void)self;

    if (argc < 2) {
        return JS_FALSE;
    }

    size_t length = 0;
    const char* code = JS_ToCStringLen(ctx, &length, argv[0]);
    const char* name = JS_ToCString(ctx, argv[1]);
    int ok = 0;

    if (code && name) {
        u64 outer = g_js_deadline;
        u64 began = get_ticks();

        g_js_deadline = began + JS_SCRIPT_MS;

        JSValue value = JS_Eval(ctx, code, length, name, JS_EVAL_TYPE_GLOBAL);

        ok = !JS_IsException(value);

        if (!ok) {
            js_report_exception(name);
        }

        JS_FreeValue(ctx, value);

        /* The caller's own time limit carries on from here. */
        g_js_deadline = outer + (get_ticks() - began);
    }

    if (code) JS_FreeCString(ctx, code);
    if (name) JS_FreeCString(ctx, name);

    return JS_NewBool(ctx, ok);
}

static JSValue native_navigate(JSContext* ctx, JSValueConst self, int argc, JSValueConst* argv) {
    (void)self;

    if (argc >= 1) {
        const char* url = JS_ToCString(ctx, argv[0]);

        if (url) {
            str_copy(g_js_nav, url, sizeof(g_js_nav));
            g_js_nav_pending = 1;
            JS_FreeCString(ctx, url);
        }
    }

    return JS_UNDEFINED;
}

static JSValue native_back(JSContext* ctx, JSValueConst self, int argc, JSValueConst* argv) {
    (void)ctx;
    (void)self;
    (void)argc;
    (void)argv;

    g_js_back_pending = 1;

    return JS_UNDEFINED;
}

static JSValue native_url(JSContext* ctx, JSValueConst self, int argc, JSValueConst* argv) {
    (void)self;
    (void)argc;
    (void)argv;

    return JS_NewString(ctx, g_url);
}

static JSValue native_now(JSContext* ctx, JSValueConst self, int argc, JSValueConst* argv) {
    (void)self;
    (void)argc;
    (void)argv;

    return JS_NewFloat64(ctx, (double)(get_ticks() - g_js_page_start));
}

static JSValue native_alert(JSContext* ctx, JSValueConst self, int argc, JSValueConst* argv) {
    (void)self;

    const char* message = argc >= 1 ? JS_ToCString(ctx, argv[0]) : 0;

    js_modal(message ? message : "", 0);

    if (message) JS_FreeCString(ctx, message);

    return JS_UNDEFINED;
}

static JSValue native_confirm(JSContext* ctx, JSValueConst self, int argc, JSValueConst* argv) {
    (void)self;

    const char* message = argc >= 1 ? JS_ToCString(ctx, argv[0]) : 0;
    int answer = js_modal(message ? message : "", 1);

    if (message) JS_FreeCString(ctx, message);

    return JS_NewBool(ctx, answer);
}

static JSValue native_title(JSContext* ctx, JSValueConst self, int argc, JSValueConst* argv) {
    (void)self;

    if (argc >= 1) {
        const char* title = JS_ToCString(ctx, argv[0]);

        if (title) {
            char clean[sizeof(g_title)];
            u32 n = 0;

            for (const char* p = title; *p && n + 1u < sizeof(clean); p++) {
                clean[n++] = ((u8)*p < 32u || (u8)*p > 126u) ? '?' : *p;
            }

            clean[n] = 0;

            if (!str_equal(clean, g_title)) {
                str_copy(g_title, clean, sizeof(g_title));
                update_title();
            }

            JS_FreeCString(ctx, title);
        }
    }

    return JS_UNDEFINED;
}

static JSValue native_status(JSContext* ctx, JSValueConst self, int argc, JSValueConst* argv) {
    (void)self;

    if (argc >= 1) {
        const char* message = JS_ToCString(ctx, argv[0]);

        if (message) {
            set_status(message);
            JS_FreeCString(ctx, message);
        }
    }

    return JS_UNDEFINED;
}

static JSValue native_size(JSContext* ctx, JSValueConst self, int argc, JSValueConst* argv) {
    (void)self;
    (void)argc;
    (void)argv;

    JSValue pair = JS_NewArray(ctx);

    JS_SetPropertyUint32(ctx, pair, 0, JS_NewInt32(ctx, text_width()));
    JS_SetPropertyUint32(ctx, pair, 1, JS_NewInt32(ctx, view_height()));

    return pair;
}

