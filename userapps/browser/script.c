/* A click on element `node` (0: the page background). Returns 1 if the
   browser should do nothing more with the click. */
static int js_click(u32 node) {
    int flags;

    if (node) {
        JSValue arg = JS_NewInt32(g_js, (int)node);

        flags = js_call_int("__click", 1, &arg, JS_EVENT_MS);
    } else {
        flags = js_call_int("__clickAway", 0, 0, JS_EVENT_MS);
    }

    g_js_focus = (flags & 2) != 0;

    return flags & 1;
}

/* A key. Returns 1 if the page used it. */
static int js_key(u32 key) {
    int code = 0;
    char ch[2] = { 0, 0 };

    if (key >= 32u && key < 127u) {
        ch[0] = (char)key;
        code = (key >= 'a' && key <= 'z') ? (int)key - 32 : (int)key;
    } else {
        switch (key) {
            case NAQ_KEY_ENTER:     code = 13; break;
            case NAQ_KEY_BACKSPACE: code = 8; break;
            case NAQ_KEY_ESCAPE:    code = 27; break;
            case '\t':              code = 9; break;
            case NAQ_KEY_LEFT:      code = 37; break;
            case NAQ_KEY_UP:        code = 38; break;
            case NAQ_KEY_RIGHT:     code = 39; break;
            case NAQ_KEY_DOWN:      code = 40; break;
            case NAQ_KEY_PAGE_UP:   code = 33; break;
            case NAQ_KEY_PAGE_DOWN: code = 34; break;
            case NAQ_KEY_END:       code = 35; break;
            case NAQ_KEY_HOME:      code = 36; break;
            case NAQ_KEY_DELETE:    code = 46; break;
            default:
                return 0;       /* control keys belong to the browser */
        }
    }

    JSValue args[2];

    args[0] = JS_NewInt32(g_js, code);
    args[1] = JS_NewString(g_js, ch);

    int flags = js_call_int("__key", 2, args, JS_EVENT_MS);

    JS_FreeValue(g_js, args[1]);

    g_js_focus = (flags & 2) != 0;

    return flags & 1;
}

/* Carries out a move to another page that a script asked for. Returns 1
   if the browser went somewhere. */
static int js_follow(void) {
    if (g_js_back_pending) {
        g_js_back_pending = 0;
        g_js_nav_pending = 0;
        go_back();
        return 1;
    }

    if (g_js_nav_pending) {
        char target[URL_MAX];

        g_js_nav_pending = 0;
        str_copy(target, g_js_nav, sizeof(target));
        navigate(target, 1);
        return 1;
    }

    return 0;
}

/*
 * Called from the main loop: runs timers that are due and redraws the
 * page if scripts changed it. Returns 1 if the window needs painting.
 */
static int js_pump(void) {
    u64 now = get_ticks();
    int repaint = 0;

    if (now >= g_js_next_tick) {
        int wait = js_call_int("__tick", 0, 0, JS_EVENT_MS);

        now = get_ticks();
        g_js_next_tick = wait < 0 ? now + 250u : now + (u64)wait;
    }

    if (!g_js_active) {
        return 1;
    }

    if (js_follow()) {
        return 1;
    }

    if (now >= g_js_next_flush) {
        if (js_flush(0)) {
            u64 took = get_ticks() - now;

            /* a big page is not laid out again more often than it can bear */
            g_js_next_flush = get_ticks() + (took * 4u > 30u ? took * 4u : 30u);
            repaint = 1;

            if (pictures_pending()) {
                load_pictures();
            }
        }
    }

    return repaint;
}

/* The page shown for "about:console": what scripts logged. */
static u32 js_log_page(char* out, u32 size) {
    u32 n = 0;

    out[0] = 0;
    str_append(out, "<title>Script log</title><h2>Script log</h2><p>Messages and errors from the scripts of ", size);
    str_append(out, g_js_log_page[0] ? g_js_log_page : "the last page", size);
    str_append(out, g_js_log_len ? ".</p><pre>" : ".</p><p>Nothing was logged.</p><pre>", size);

    n = (u32)strlen(out);

    for (u32 i = 0; i < g_js_log_len && n + 8u < size; i++) {
        char c = g_js_log[i];

        if (c == '<') {
            out[n++] = '&'; out[n++] = 'l'; out[n++] = 't'; out[n++] = ';';
        } else if (c == '&') {
            out[n++] = '&'; out[n++] = 'a'; out[n++] = 'm'; out[n++] = 'p'; out[n++] = ';';
        } else {
            out[n++] = c;
        }
    }

    out[n] = 0;
    str_append(out, "</pre>", size);

    return (u32)strlen(out);
}
