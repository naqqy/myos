/*
 * NAQ OS Browser: JavaScript.
 *
 * This file is part of BROWSER.ELF (browser.c includes it). It runs the
 * scripts of a page in the QuickJS engine (third_party/quickjs).
 *
 * How the pieces fit:
 *
 *   browser.c   fetches the page and draws it from its HTML, as before.
 *   dom.js      runs inside the engine. It builds the document tree that
 *               scripts work on and provides window, document, events,
 *               timers and the rest. It is compiled into the program.
 *   this file   starts the engine for each page, gives dom.js the few
 *               things only the browser can do (fetch a file, show a
 *               message, go to an address), and passes clicks, keys and
 *               the passing of time to it.
 *
 * When scripts change the document, dom.js hands back new HTML and the
 * page is laid out again from that.
 *
 * Limits worth knowing:
 *   - Every page gets a fresh engine with a fixed amount of memory.
 *   - A script that runs too long is stopped, so a page cannot hang the
 *     browser. After a few such stops the page's scripts are switched off.
 *   - There is no layout information for scripts (sizes and positions
 *     read as 0), no canvas, no modules, and only GET requests.
 */

#include <stdlib.h>
#include "quickjs.h"
#include "dom_js.h"     /* generated by build.sh from dom.js: g_dom_js[] */

#define JS_HEAP_BYTES     (64u * 1024u * 1024u)
#define JS_LOG_MAX        (48u * 1024u)
#define JS_STACK_BYTES    (2u * 1024u * 1024u)

#define JS_BOOT_MS        15000u    /* building the document tree */
#define JS_SCRIPT_MS      5000u     /* one script of the page */
#define JS_EVENT_MS       2000u     /* one click, key or batch of timers */
#define JS_PAGE_LOAD_MS   25000u    /* all script files of a page together */
#define JS_MAX_TIMEOUTS   3
#define JS_MAX_LOADS      30

static u8 g_js_heap[JS_HEAP_BYTES];

static JSRuntime* g_js_rt = 0;
static JSContext* g_js = 0;

static int g_js_enabled = 1;        /* the toolbar switch */
static int g_js_active = 0;         /* this page has a running engine */
static int g_js_focus = 0;          /* a text box on the page has the keyboard */

static u64 g_js_deadline = 0;       /* a running script is stopped after this */
static u64 g_js_page_start = 0;
static u64 g_js_load_until = 0;
static u32 g_js_loads = 0;
static int g_js_timeouts = 0;
static u32 g_js_scripts = 0;
static u32 g_js_errors = 0;

static u64 g_js_next_tick = 0;
static u64 g_js_next_flush = 0;

static char g_js_nav[URL_MAX];
static int g_js_nav_pending = 0;
static int g_js_back_pending = 0;

static char g_js_log[JS_LOG_MAX];
static u32 g_js_log_len = 0;
static char g_js_log_page[URL_MAX] = "";


/* -------------------------------------------------------------------------- */
/* The script log                                                              */
/* -------------------------------------------------------------------------- */

static void js_log(const char* level, const char* message) {
    u32 need = (u32)strlen(level) + (u32)strlen(message) + 4u;

    if (need > JS_LOG_MAX / 4u) {
        need = JS_LOG_MAX / 4u;
    }

    /* Full: drop the older half. */
    if (g_js_log_len + need + 1u >= JS_LOG_MAX) {
        u32 cut = g_js_log_len / 2u;

        while (cut < g_js_log_len && g_js_log[cut] != '\n') {
            cut++;
        }

        if (cut < g_js_log_len) {
            cut++;
        }

        for (u32 i = cut; i < g_js_log_len; i++) {
            g_js_log[i - cut] = g_js_log[i];
        }

        g_js_log_len -= cut;
    }

    u32 room = JS_LOG_MAX - g_js_log_len - 1u;
    u32 n = 0;
    char* out = g_js_log + g_js_log_len;

    if (room < 8u) {
        return;
    }

    if (level[0] && !str_equal(level, "log")) {
        out[n++] = '[';

        for (const char* p = level; *p && n + 3u < room; p++) {
            out[n++] = *p;
        }

        out[n++] = ']';
        out[n++] = ' ';
    }

    for (const char* p = message; *p && n + 1u < room && n < need; p++) {
        out[n++] = *p;
    }

    out[n++] = '\n';
    g_js_log_len += n;
    g_js_log[g_js_log_len] = 0;

    if (str_equal(level, "error")) {
        g_js_errors++;
    }
}

/*
 * Logs the exception waiting in the engine. Returns 1 if it was the
 * "took too long" stop rather than an ordinary error.
 */
static int js_report_exception(const char* where) {
    JSValue error = JS_GetException(g_js);
    int stopped = get_ticks() > g_js_deadline;
    char line[600];

    line[0] = 0;

    if (stopped) {
        str_append(line, "Stopped ", sizeof(line));
        str_append(line, where, sizeof(line));
        str_append(line, ": it ran for too long", sizeof(line));
        g_js_timeouts++;
    } else {
        const char* text = JS_ToCString(g_js, error);

        str_append(line, "Uncaught ", sizeof(line));
        str_append(line, text ? text : "error", sizeof(line));

        if (text) {
            JS_FreeCString(g_js, text);
        }

        if (JS_IsObject(error)) {
            JSValue stack = JS_GetPropertyStr(g_js, error, "stack");

            if (JS_IsString(stack)) {
                const char* trace = JS_ToCString(g_js, stack);

                if (trace && trace[0]) {
                    str_append(line, "\n", sizeof(line));
                    str_append(line, trace, sizeof(line));
                }

                if (trace) {
                    JS_FreeCString(g_js, trace);
                }
            }

            JS_FreeValue(g_js, stack);
        }

        /* the trace ends with a newline of its own */
        u32 n = (u32)strlen(line);

        while (n > 0 && (line[n - 1u] == '\n' || line[n - 1u] == ' ')) {
            line[--n] = 0;
        }
    }

    JS_FreeValue(g_js, error);
    js_log("error", line);

    return stopped;
}

