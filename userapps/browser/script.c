/* Running the engine                                                          */
/* -------------------------------------------------------------------------- */

/* Called by the engine every so often while a script runs. */
static int js_interrupt(JSRuntime* rt, void* opaque) {
    (void)rt;
    (void)opaque;

    return get_ticks() > g_js_deadline;
}

static void js_rejection(JSContext* ctx, JSValueConst promise, JSValueConst reason,
                         int is_handled, void* opaque) {
    (void)promise;
    (void)opaque;

    if (!is_handled) {
        const char* text = JS_ToCString(ctx, reason);
        char line[300];

        line[0] = 0;
        str_append(line, "Possibly unhandled promise rejection: ", sizeof(line));
        str_append(line, text ? text : "?", sizeof(line));
        js_log("warn", line);

        if (text) JS_FreeCString(ctx, text);
    }
}

/* Promise callbacks and other queued work run after each call. */
static void js_run_jobs(void) {
    for (u32 n = 0; n < 100000u; n++) {
        JSContext* ctx = 0;
        int r = JS_ExecutePendingJob(g_js_rt, &ctx);

        if (r == 0) {
            break;
        }

        if (r < 0 && js_report_exception("a queued task")) {
            break;
        }
    }
}

static void js_stop(void) {
    g_js_active = 0;
    g_js_focus = 0;
    g_js = 0;
    g_js_rt = 0;
    g_js_nav_pending = 0;
    g_js_back_pending = 0;
}

/*
 * Calls a function that dom.js defined. The result must be freed by the
 * caller; on an error it is JS_UNDEFINED.
 */
static JSValue js_call(const char* name, int argc, JSValueConst* argv, u32 limit_ms) {
    JSValue global = JS_GetGlobalObject(g_js);
    JSValue fn = JS_GetPropertyStr(g_js, global, name);

    g_js_deadline = get_ticks() + limit_ms;

    JSValue result = JS_Call(g_js, fn, global, argc, argv);

    if (JS_IsException(result)) {
        js_report_exception(name);
        result = JS_UNDEFINED;
    }

    JS_FreeValue(g_js, fn);
    JS_FreeValue(g_js, global);

    g_js_deadline = get_ticks() + limit_ms;
    js_run_jobs();

    /* whatever just ran may have set a timer */
    g_js_next_tick = 0;

    if (g_js_timeouts >= JS_MAX_TIMEOUTS && g_js_active) {
        g_js_active = 0;
        g_js_focus = 0;
        js_log("error", "The scripts of this page were switched off: they kept running too long");
        set_status("The scripts of this page were stopped: they kept running too long.");
    }

    return result;
}

static int js_call_int(const char* name, int argc, JSValueConst* argv, u32 limit_ms) {
    JSValue result = js_call(name, argc, argv, limit_ms);
    int value = 0;

    if (JS_ToInt32(g_js, &value, result) < 0) {
        JSValue ignored = JS_GetException(g_js);

        JS_FreeValue(g_js, ignored);
        value = 0;
    }

    JS_FreeValue(g_js, result);

    return value;
}

/*
 * Asks dom.js for the page as HTML if scripts changed it, and draws that.
 * Returns 1 if the page was laid out again.
 */
static int js_flush(int force) {
    JSValue arg = JS_NewBool(g_js, force);
    JSValue html = js_call("__flush", 1, &arg, JS_EVENT_MS);
    int changed = 0;

    if (JS_IsString(html)) {
        size_t length = 0;
        const char* text = JS_ToCStringLen(g_js, &length, html);

        if (text) {
            if (length >= PAGE_MAX) {
                length = PAGE_MAX - 1u;
            }

            memcpy(g_html, text, length);
            g_html[length] = 0;
            g_html_len = (u32)length;

            JS_FreeCString(g_js, text);

            rerender((u32)length);
            changed = 1;
        }
    }

    JS_FreeValue(g_js, html);

    return changed;
}

/* Does the page have anything for the engine to do? */
static int js_page_needs_engine(const char* html, u32 length) {
    static const char* const marks[] = {
        "<script", "<input", "<button", "<select", "<textarea", " onclick", " onload"
    };

    for (u32 i = 0; i + 9u < length; i++) {
        if (html[i] != '<' && html[i] != ' ') {
            continue;
        }

        for (u32 m = 0; m < sizeof(marks) / sizeof(marks[0]); m++) {
            const char* mark = marks[m];
            u32 k = 0;

            while (mark[k] && lower(html[i + k]) == mark[k]) {
                k++;
            }

            if (!mark[k]) {
                return 1;
            }
        }
    }

    return 0;
}

/*
 * Starts an engine for the page in g_html (already on screen) and runs
 * its scripts.
 */
static void js_run_page(void) {
    js_stop();

    if (!g_js_enabled || !js_page_needs_engine(g_html, g_html_len)) {
        return;
    }

    char saved[160];

    str_copy(saved, g_status, sizeof(saved));
    set_status("Running the page's scripts...");
    paint_now();

    g_js_log_len = 0;
    g_js_log[0] = 0;
    g_js_errors = 0;
    g_js_scripts = 0;
    g_js_timeouts = 0;
    g_js_loads = 0;
    str_copy(g_js_log_page, g_url, sizeof(g_js_log_page));

    g_js_page_start = get_ticks();
    g_js_load_until = g_js_page_start + JS_PAGE_LOAD_MS;
    g_js_next_tick = 0;
    g_js_next_flush = 0;

    /* A fresh heap for every page: nothing of the last page survives. */
    naq_heap_init(g_js_heap, sizeof(g_js_heap));

    g_js_rt = JS_NewRuntime();

    if (!g_js_rt) {
        js_log("error", "The script engine could not start");
        str_copy(g_status, saved, sizeof(g_status));
        return;
    }

    JS_SetMaxStackSize(g_js_rt, JS_STACK_BYTES);
    JS_SetInterruptHandler(g_js_rt, js_interrupt, 0);
    JS_SetHostPromiseRejectionTracker(g_js_rt, js_rejection, 0);

    g_js = JS_NewContext(g_js_rt);

    if (!g_js) {
        js_log("error", "The script engine could not start");
        js_stop();
        str_copy(g_status, saved, sizeof(g_status));
        return;
    }

    JSValue global = JS_GetGlobalObject(g_js);
    JSValue native = JS_NewObject(g_js);

    JS_SetPropertyFunctionList(g_js, native, g_native_functions,
                               sizeof(g_native_functions) / sizeof(g_native_functions[0]));
    JS_SetPropertyStr(g_js, global, "__native", native);
    JS_FreeValue(g_js, global);

    g_js_deadline = get_ticks() + JS_BOOT_MS;

    JSValue loaded = JS_Eval(g_js, (const char*)g_dom_js, sizeof(g_dom_js) - 1u,
                             "dom.js", JS_EVAL_TYPE_GLOBAL);

    if (JS_IsException(loaded)) {
        js_report_exception("dom.js");
        js_stop();
        str_copy(g_status, saved, sizeof(g_status));
        return;
    }

    JS_FreeValue(g_js, loaded);

    g_js_active = 1;

    JSValue html = JS_NewStringLen(g_js, g_html, g_html_len);

    JS_FreeValue(g_js, js_call("__boot", 1, &html, JS_BOOT_MS));
    JS_FreeValue(g_js, html);

    if (g_js_active) {
        /* each script has its own limit (see native_eval) */
        g_js_scripts = (u32)js_call_int("__runScripts", 0, 0, JS_PAGE_LOAD_MS + 60000u);
    }

    str_copy(g_status, saved, sizeof(g_status));

    if (g_js_active) {
        js_flush(0);
    }

    /* What happened, after the security note. */
    if (g_js_scripts || g_js_errors) {
        char note[96];
        char digits[12];

        note[0] = 0;
        str_append(note, " Scripts: ", sizeof(note));
        snprintf(digits, sizeof(digits), "%u", g_js_scripts);
        str_append(note, digits, sizeof(note));
        str_append(note, " run", sizeof(note));

        if (g_js_errors) {
            snprintf(digits, sizeof(digits), "%u", g_js_errors);
            str_append(note, ", ", sizeof(note));
            str_append(note, digits, sizeof(note));
            str_append(note, g_js_errors == 1 ? " error (see Log)." : " errors (see Log).", sizeof(note));
        } else {
            str_append(note, ".", sizeof(note));
        }

        str_append(g_status, note, sizeof(g_status));
    }
}

